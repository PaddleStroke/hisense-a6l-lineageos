# Hisense A6L radio (agent ril): generate "not supported by default" base classes for the AIDL
# radio interfaces that libminradio does not cover (messaging, voice), from the frozen AIDL API.
#
# usage: gen_bases.py <hardware/interfaces/radio/aidl/aidl_api> <version> <outdir>
# Every request method gets an override that answers REQUEST_NOT_SUPPORTED with default-constructed
# response arguments, so the framework never waits for a missing response. Hand-written classes
# (hal/RadioVoice.cpp, hal/RadioMessaging.cpp) override what is implemented.
import os
import re
import sys

PRIM = {'int': 'int32_t', 'long': 'int64_t', 'boolean': 'bool', 'byte': 'int8_t', 'float': 'float',
        'double': 'double', 'char': 'char16_t', 'String': 'std::string'}


def aidl_path(api, ver, fq):
    parts = fq.split('.')
    pkg = '.'.join(parts[:-1])
    return os.path.join(api, pkg, ver, *parts[:-1], parts[-1] + '.aidl')


def is_enum(api, ver, fq):
    p = aidl_path(api, ver, fq)
    if not os.path.exists(p):
        return False
    body = open(p).read()
    return re.search(r'^\s*enum\s+\w+', body, re.M) is not None


def cxx_type(api, ver, t):
    arr = t.endswith('[]')
    base = t[:-2] if arr else t
    if base == 'byte' and arr:
        return 'std::vector<uint8_t>', False
    if base in PRIM:
        c = PRIM[base]
        by_value = (not arr) and base != 'String'
    else:
        c = '::aidl::' + base.replace('.', '::')
        by_value = (not arr) and is_enum(api, ver, base)
    if arr:
        return 'std::vector<%s>' % c, False
    return c, by_value


def parse_methods(path):
    txt = open(path).read()
    txt = re.sub(r'/\*.*?\*/', '', txt, flags=re.S)
    txt = re.sub(r'//.*', '', txt)
    out = []
    for m in re.finditer(r'oneway\s+void\s+(\w+)\s*\((.*?)\)\s*;', txt, re.S):
        name, args = m.group(1), m.group(2).strip()
        params = []
        if args:
            for a in args.split(','):
                a = re.sub(r'@\w+(\([^)]*\))?', '', a).strip()
                a = re.sub(r'^(in|out|inout)\s+', '', a)
                typ, nm = a.rsplit(None, 1)
                params.append((typ.strip(), nm.strip(), '@nullable' in m.group(2) and False))
        out.append((name, params, args))
    return out


def nullable_params(path):
    txt = open(path).read()
    res = set()
    for m in re.finditer(r'oneway\s+void\s+(\w+)\s*\((.*?)\)\s*;', txt, re.S):
        for a in m.group(2).split(','):
            if '@nullable' in a:
                res.add((m.group(1), a.strip().split()[-1]))
    return res


def gen(api, ver, pkg, iface, outdir, special=None):
    special = special or {}
    base = os.path.join(api, 'android.hardware.radio.' + pkg, ver, 'android', 'hardware', 'radio', pkg)
    req = parse_methods(os.path.join(base, 'I%s.aidl' % iface))
    req_null = nullable_params(os.path.join(base, 'I%s.aidl' % iface))
    resp_path = os.path.join(base, 'I%sResponse.aidl' % iface)
    resp = {n: p for n, p, _ in parse_methods(resp_path)}
    resp_null = nullable_params(resp_path)
    ns = '::aidl::android::hardware::radio::' + pkg
    cls = '%sBase' % iface
    lines = []
    w = lines.append
    w('// SPDX-License-Identifier: Apache-2.0')
    w('// GENERATED by hal/gen/gen_bases.py from aidl_api/android.hardware.radio.%s/%s - do not edit.' % (pkg, ver))
    w('#pragma once')
    w('')
    w('#include <aidl/android/hardware/radio/%s/BnRadio%s.h>' % (pkg, iface[5:]))
    w('#include <aidl/android/hardware/radio/%s/IRadio%sResponse.h>' % (pkg, iface[5:]))
    w('#include <aidl/android/hardware/radio/%s/IRadio%sIndication.h>' % (pkg, iface[5:]))
    w('#include <android-base/logging.h>')
    w('#include <libminradio/GuaranteedCallback.h>')
    w('#include <libminradio/RadioSlotBase.h>')
    w('#include <libminradio/response.h>')
    w('')
    w('namespace android::hardware::radio::a6l {')
    w('')
    w('class %s : public ::android::hardware::radio::minimal::RadioSlotBase,' % cls)
    w('             public %s::Bn%s {' % (ns, iface))
    w('  public:')
    w('    using ::android::hardware::radio::minimal::RadioSlotBase::RadioSlotBase;')
    w('')
    w('  protected:')
    w('    ::android::hardware::radio::minimal::GuaranteedCallback<%s::I%sIndication, %s::I%sIndicationDefault, true> indicate;' % (ns, iface, ns, iface))
    w('    ::android::hardware::radio::minimal::GuaranteedCallback<%s::I%sResponse, %s::I%sResponseDefault> respond;' % (ns, iface, ns, iface))
    w('')
    w('    ::ndk::ScopedAStatus setResponseFunctions(')
    w('            const std::shared_ptr<%s::I%sResponse>& response,' % (ns, iface))
    w('            const std::shared_ptr<%s::I%sIndication>& indication) override {' % (ns, iface))
    w('        respond = response;')
    w('        indicate = indication;')
    w('        setResponseFunctionsBase();')
    w('        return ::ndk::ScopedAStatus::ok();')
    w('    }')
    w('    ::ndk::ScopedAStatus responseAcknowledgement() override { return ::ndk::ScopedAStatus::ok(); }')
    w('')
    count = 0
    for name, params, _ in req:
        if name in ('setResponseFunctions', 'responseAcknowledgement'):
            continue
        rname = special.get(name, name + 'Response')
        if rname not in resp:
            raise SystemExit('no response for %s (%s)' % (name, rname))
        sig = []
        for typ, nm, _ in params:
            c, byval = cxx_type(api, ver, typ)
            if (name, nm) in req_null:
                c, byval = 'std::optional<%s>' % c, False
            sig.append(('%s' if byval else 'const %s&') % c + ' in_' + nm)
        rargs = ['::android::hardware::radio::minimal::notSupported(in_serial)']
        for typ, nm, _ in resp[rname][1:]:
            c, _ = cxx_type(api, ver, typ)
            if (rname, nm) in resp_null:
                c = 'std::optional<%s>' % c
            rargs.append('%s{}' % c)
        w('    ::ndk::ScopedAStatus %s(%s) override {' % (name, ', '.join(sig)))
        unused = [s.split()[-1] for s in sig[1:]]
        for u in unused:
            w('        (void)%s;' % u)
        w('        LOG(INFO) << "[" << in_serial << "] %s.%s (not supported)";' % (iface, name))
        w('        respond()->%s(%s);' % (rname, ', '.join(rargs)))
        w('        return ::ndk::ScopedAStatus::ok();')
        w('    }')
        count += 1
    w('};')
    w('')
    w('}  // namespace android::hardware::radio::a6l')
    os.makedirs(outdir, exist_ok=True)
    out = os.path.join(outdir, '%s.h' % cls)
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('%s: %d methods' % (out, count))


if __name__ == '__main__':
    api, ver, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
    gen(api, ver, 'voice', 'RadioVoice', outdir, {'hangup': 'hangupConnectionResponse'})
    gen(api, ver, 'messaging', 'RadioMessaging', outdir)
